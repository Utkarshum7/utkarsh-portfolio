#!/usr/bin/env node
// Build activity snapshot: public commits by the owner on the default branch of each repository this site links
// (src/data/repos.json), over the last 52 weeks. Writes src/data/activity.json.
//
//   node scripts/github-activity.mjs
//
// Uses the public GitHub REST API WITHOUT a token, on purpose: a repository that isn't public returns 404 and is
// skipped, so private work can never leak into the snapshot. Stores dates and counts only (no commit messages).
// The snapshot is static; the page states when it was taken.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const OWNER = 'Utkarshum7';
export const WEEKS = 52;
const DAY = 86_400_000;

/** UTC day key, e.g. 2026-10-08 */
export const dayKey = (d) => new Date(d).toISOString().slice(0, 10);

/**
 * Aggregate commit timestamps into a calendar: `WEEKS` full weeks (Sunday first) ending with the week of `now`.
 * Returns { start, end, days: number[] } where days[i] is the commit count on start + i days.
 */
export function calendar(dates, now = new Date()) {
  const today = Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate());
  const endOfWeek = today + (6 - new Date(today).getUTCDay()) * DAY;
  const start = endOfWeek - (WEEKS * 7 - 1) * DAY;
  const days = new Array(WEEKS * 7).fill(0);
  for (const d of dates) {
    const t = Date.parse(d);
    const day = Date.UTC(new Date(t).getUTCFullYear(), new Date(t).getUTCMonth(), new Date(t).getUTCDate());
    const i = Math.round((day - start) / DAY);
    if (i >= 0 && i < days.length && day <= today) days[i]++;
  }
  return { start: dayKey(start), end: dayKey(today), days };
}

async function getJson(url) {
  const res = await fetch(url, {
    headers: { Accept: 'application/vnd.github+json', 'User-Agent': 'portfolio-activity' },
  });
  if (res.status === 404) return { status: 404 };
  if (!res.ok)
    throw new Error(
      `${res.status} for ${url} (rate limit remaining: ${res.headers.get('x-ratelimit-remaining')})`,
    );
  return {
    status: 200,
    body: await res.json(),
    next: res.headers.get('link')?.match(/<([^>]+)>;\s*rel="next"/)?.[1],
  };
}

export async function collect({ repos, now = new Date(), log = console.log }) {
  const since = new Date(now.getTime() - (WEEKS * 7 + 7) * DAY).toISOString();
  const all = [];
  const out = [];
  for (const [key, { url }] of Object.entries(repos)) {
    const name = new URL(url).pathname.split('/')[2];
    const meta = await getJson(`https://api.github.com/repos/${OWNER}/${name}`);
    if (meta.status === 404 || meta.body.private) {
      log(`skip ${key}: not public`);
      continue;
    }
    const dates = [];
    let next = `https://api.github.com/repos/${OWNER}/${name}/commits?author=${OWNER}&since=${since}&per_page=100`;
    while (next) {
      const page = await getJson(next);
      if (page.status === 404) break;
      for (const c of page.body) dates.push(c.commit?.author?.date ?? c.commit?.committer?.date);
      next = page.next;
    }
    const cal = calendar(dates, now);
    const inWindow = cal.days.reduce((a, b) => a + b, 0);
    all.push(...dates);
    out.push({
      key,
      language: meta.body.language ?? null,
      commits: inWindow,
      lastCommit: dates.length ? dayKey(dates.map((d) => Date.parse(d)).sort((a, b) => b - a)[0]) : null,
      pushedAt: meta.body.pushed_at ? dayKey(meta.body.pushed_at) : null,
    });
    log(`${key}: ${inWindow} commits in window`);
  }
  const cal = calendar(all, now);
  return {
    $comment:
      'Generated by scripts/github-activity.mjs from the public GitHub API (no token). Owner commits on default branches of the repositories in repos.json. Dates are UTC.',
    generatedAt: now.toISOString(),
    weeks: WEEKS,
    start: cal.start,
    end: cal.end,
    total: cal.days.reduce((a, b) => a + b, 0),
    days: cal.days,
    repos: out,
  };
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isMain) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const { $comment, ...repos } = JSON.parse(fs.readFileSync(path.join(root, 'src/data/repos.json'), 'utf8'));
  void $comment;
  const snapshot = await collect({ repos });
  fs.writeFileSync(path.join(root, 'src/data/activity.json'), JSON.stringify(snapshot, null, 2) + '\n');
  console.log(
    `activity: ${snapshot.total} commits across ${snapshot.repos.length} public repositories → src/data/activity.json`,
  );
}
